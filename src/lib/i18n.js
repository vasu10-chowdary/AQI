const DICTIONARIES = { en: EN, hi: HI, kn: KN };

/**
 * Look up a translated UI string.
 *
 * @param {string} key
 * @param {'en'|'hi'|'kn'} [lang]
 * @param {Record<string, string|number>} [vars]
 */
export function t(key, lang = 'en', vars) {
  const dictionary = DICTIONARIES[lang] || EN;
  const template = dictionary[key] ?? EN[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

export function localeFor(lang) {
  return (LANGUAGES.find((entry) => entry.id === lang) || LANGUAGES[0]).locale;
}

export function htmlLangFor(lang) {
  return (LANGUAGES.find((entry) => entry.id === lang) || LANGUAGES[0]).htmlLang;
}

/** "3 pm" style hour label, localised. */
export function formatHour(hour, lang = 'en') {
  try {
    const date = new Date(2024, 0, 1, hour, 0, 0);
    return new Intl.DateTimeFormat(localeFor(lang), {
      hour: 'numeric',
      hour12: true,
    }).format(date);
  } catch {
    return `${hour}:00`;
  }
}

/**
 * Format an Open-Meteo local timestamp ("2026-11-17T15:00") as a clock time
 * without letting the browser's timezone shift it.
 */
export function formatLocalTime(timestamp, lang = 'en') {
  const match = /T(\d{2}):(\d{2})/.exec(String(timestamp ?? ''));
  if (!match) return '—';
  const hour = Number(match[1]);
  const minute = Number(match[2]);
  try {
    const date = new Date(2024, 0, 1, hour, minute);
    return new Intl.DateTimeFormat(localeFor(lang), {
      hour: 'numeric',
      minute: '2-digit',
      hour12: true,
    }).format(date);
  } catch {
    return `${match[1]}:${match[2]}`;
  }
}
